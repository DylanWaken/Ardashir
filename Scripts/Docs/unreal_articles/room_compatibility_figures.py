def text(x, y, value, size=19, fill=INK, anchor="start"):
    return f'<text x="{x}" y="{y}" font-size="{size}" fill="{fill}" text-anchor="{anchor}">{escape(str(value))}</text>'


def rect(x, y, w, h, fill="#e8e5dc", stroke=INK, extra=""):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}" stroke="{stroke}" stroke-width="2" {extra}/>'


def path(d, fill="none", stroke=INK, width=2, extra=""):
    return f'<path d="{d}" fill="{fill}" stroke="{stroke}" stroke-width="{width}" {extra}/>'


def poly(points, fill="#c9d4c1", stroke=INK):
    return f'<polygon points="{points}" fill="{fill}" stroke="{stroke}" stroke-width="2"/>'


def circle(x, y, r, fill=GOLD, stroke=INK):
    return f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{r}" fill="{fill}" stroke="{stroke}" stroke-width="1.5"/>'


def line(x1, y1, x2, y2, stroke=INK, width=2, extra=""):
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{stroke}" stroke-width="{width}" {extra}/>'


def group(body, x=0, y=0, scale=1):
    return f'<g transform="translate({x} {y}) scale({scale})">{body}</g>'


def cube(x, y, w=130, h=100, depth=38, color="#c9d4c1", wire=False):
    s = poly(f"{x},{y} {x+depth},{y-depth} {x+w+depth},{y-depth} {x+w},{y}", "#e5e8dc")
    s += poly(f"{x+w},{y} {x+w+depth},{y-depth} {x+w+depth},{y+h-depth} {x+w},{y+h}", "#9eafa2")
    s += rect(x,y,w,h,color)
    if wire:
        s += line(x,y,x+w,y+h) + line(x,y,x+w+depth,y-depth) + line(x+w,y,x+w+depth,y+h-depth)
    return s


def arrow(x1,y1,x2,y2):
    return line(x1,y1,x2,y2,GOLD,3, 'marker-end="url(#arrow)"')


