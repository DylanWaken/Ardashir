def svg(record):
    name,title,fixture,status,draw=record
    desc=f"Schematic {title.lower()} in the same red/green-walled indoor room. {status}. The left plan locates the example; the right drawing explains its representation."
    body=f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 500" role="img" aria-labelledby="title desc"><title id="title">{escape(title)}</title><desc id="desc">{escape(desc)}</desc>'
    body+='<defs><marker id="arrow" markerWidth="8" markerHeight="8" refX="6" refY="3" orient="auto"><path d="M0 0 L6 3 L0 6 Z" fill="#d6ad51"/></marker><radialGradient id="smoke"><stop stop-color="#748782" stop-opacity=".8"/><stop offset="1" stop-color="#748782" stop-opacity="0"/></radialGradient></defs>'
    body+='<rect width="1200" height="500" fill="#fffdf8"/><g font-family="Arial,sans-serif">'
    body+=text(24,35,title,25)+text(24,61,status+" · original explanatory SVG",16,"#626d65")
    body+=line(296,80,296,475,"#d2d8ce")+room_plan(fixture,title)+group(draw(),321,84)
    body+='</g></svg>\n'
    return body


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true")
    args=parser.parse_args()
    stale=[]
    for record in RECORDS:
        target=OUT/(record[0]+".svg"); expected=svg(record)
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8")!=expected:stale.append(str(target))
        else:target.write_text(expected,encoding="utf-8",newline="\n")
    if stale:raise SystemExit("Stale room compatibility figures:\n"+"\n".join(stale))
    print(f"{'Checked' if args.check else 'Wrote'} {len(RECORDS)} room compatibility diagrams")


if __name__=="__main__":main()
