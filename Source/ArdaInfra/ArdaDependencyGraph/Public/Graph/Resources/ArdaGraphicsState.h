/** Logical graphics values connect stages without allocating intermediate GPU storage. */
#pragma once

#include "ArdaGraph.h"
#include "RHI/Pipelines/ArdaRHIGraphicsPipeline.h"
#include "RHI/Pipelines/ArdaRHIMeshletPipeline.h"

namespace arda
{
	class FArdaGraphOperation;

	/** Stages supported by traditional and meshlet graphics dataflow assembly. */
	enum class EArdaGraphicsStage : uint8_t
	{
		None,
		Vertex,
		Raster,
		Pixel,
		Hull,
		Domain,
		Geometry,
		Amplification,
		Mesh
	};

	/** Shader interface values are distinct from addressable graph resources. */
	enum class EArdaGraphStageValueKind : uint8_t
	{
		None,
		Vertices,
		Fragments,
		Pixels,
		ControlPoints,
		MeshPayload,
		RayShader
	};

	/** Erased stage identity for registry adapters and compiler validation.
	 * A serialized identity is untrusted until the compiler checks its producer and kind.
	 * Values belong to one construction, survive queued edit scopes, and cannot enter a later frame.
	 */
	class FArdaGraphStageValue
	{
	public:
		FArdaGraphStageValue() = default;

		FArdaGraphStageValue(FArdaGraphNodeHandle Producer, EArdaGraphStageValueKind Kind)
		    : mProducer(Producer),
		      mKind(Kind)
		{
		}

		FArdaGraphNodeHandle GetProducer() const noexcept
		{
			return mProducer;
		}

		EArdaGraphStageValueKind GetKind() const noexcept
		{
			return mKind;
		}

		explicit operator bool() const noexcept
		{
			return bool(mProducer);
		}

	private:
		FArdaGraphNodeHandle mProducer;
		EArdaGraphStageValueKind mKind = EArdaGraphStageValueKind::None;
	};

	/** Typed stage output. There is deliberately no conversion between vertices and fragments. */
	template <EArdaGraphStageValueKind Kind>
	class TArdaGraphStageValue final : public FArdaGraphStageValue
	{
	public:
		TArdaGraphStageValue() = default;

	private:
		friend class FArdaGraphOperation;

		explicit TArdaGraphStageValue(FArdaGraphNodeHandle Producer)
		    : FArdaGraphStageValue(Producer, Kind)
		{
		}
	};

	/** Per-vertex shader outputs before rasterization. Reuse duplicates shader execution per draw.
	 * This is a lazy expression over graph resource identities, not a snapshot of mutable buffer contents.
	 */
	using FArdaGraphVertices = TArdaGraphStageValue<EArdaGraphStageValueKind::Vertices>;
	/** Interpolated fragment inputs generated by a raster operation. */
	using FArdaGraphFragments = TArdaGraphStageValue<EArdaGraphStageValueKind::Fragments>;
	/** Completed pixel operation, whose declared targets/buffers carry its physical results. */
	using FArdaGraphPixels = TArdaGraphStageValue<EArdaGraphStageValueKind::Pixels>;
	using FArdaGraphControlPoints = TArdaGraphStageValue<EArdaGraphStageValueKind::ControlPoints>;
	using FArdaGraphMeshPayload = TArdaGraphStageValue<EArdaGraphStageValueKind::MeshPayload>;

	/** Dynamic inputs collected from stage hooks for one compiler-generated native draw.
	 * ConfigureGraphics hooks may configure state and record setup, but must not submit or issue the draw.
	 */
	struct FArdaGraphicsWork
	{
		FArdaRHIGraphicsState mState;
		FArdaRHIDrawArguments mDraw;
		bool mbIndexed = false;
		FArdaRHIMeshletState mMeshletState;
		uint32_t mMeshGroupCountX = 1, mMeshGroupCountY = 1, mMeshGroupCountZ = 1;
	};

	/** Explicit capture capacity; the producer documents its record layout and overflow policy.
	 * Zero requests the producer's natural size. A materializer may reject an unbounded capture.
	 */
	struct FArdaStageBufferRequest
	{
		uint64_t mElementCount = 0;
	};

	constexpr EArdaGraphStageValueKind GetArdaGraphicsStageOutput(EArdaGraphicsStage Stage)
	{
		return Stage == EArdaGraphicsStage::Vertex || Stage == EArdaGraphicsStage::Domain ||
		        Stage == EArdaGraphicsStage::Geometry || Stage == EArdaGraphicsStage::Mesh
		    ? EArdaGraphStageValueKind::Vertices
		    : Stage == EArdaGraphicsStage::Hull          ? EArdaGraphStageValueKind::ControlPoints
		    : Stage == EArdaGraphicsStage::Amplification ? EArdaGraphStageValueKind::MeshPayload
		    : Stage == EArdaGraphicsStage::Raster        ? EArdaGraphStageValueKind::Fragments
		    : Stage == EArdaGraphicsStage::Pixel         ? EArdaGraphStageValueKind::Pixels
		                                                 : EArdaGraphStageValueKind::None;
	}
}
