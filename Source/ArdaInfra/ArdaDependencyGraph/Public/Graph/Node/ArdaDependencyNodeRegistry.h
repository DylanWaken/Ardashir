namespace arda
{
	class FArdaDependencyExecutionContext;
	class FArdaCudaSequence;
	class FArdaGraphEdit;
	class FArdaSubgraphContext;
	class FArdaGraphArchiveWriter;
	class FArdaGraphArchiveReader;

	namespace node_detail
	{
		template <class Derived, class Parameters, EArdaDependencyNodeKind Kind>
		class TArdaExecutionNode;
	}

	/** Framework-owned erased implementation generated from typed or portable node definitions.
	 * Registry lookup exposes a const view for graph/compiler inspection; this is not an authoring API.
	 */
	class FArdaDependencyNodeExecutable final
	{
	private:
		template <class Derived, class Parameters, EArdaDependencyNodeKind Kind>
		friend class node_detail::TArdaExecutionNode;
		friend class FArdaNodeRegistry;
		friend class FArdaRuntimeNodeDefinition;

		FArdaDependencyNodeExecutable() = default;
		FArdaDependencyNodeExecutable(FArdaDependencyNodeExecutable&&) = default;
		FArdaDependencyNodeExecutable(const FArdaDependencyNodeExecutable&) = default;
		FArdaDependencyNodeExecutable& operator=(const FArdaDependencyNodeExecutable&) = delete;

	public:
		~FArdaDependencyNodeExecutable() = default;
		eastl::string mName;
		uint32_t mVersion = 1;
		/** Complete portable implementation when authored from data; empty for native class definitions. */
		eastl::string mPortableDefinition;
		EArdaDependencyNodeKind mKind = EArdaDependencyNodeKind::Compute;
		/** Public attachment schema used for input type validation and canonical identity, before preparation.
		 * Typed registration assigns ArdaDependencyParameterType<Parameters>; execution can use a different schema.
		 */
		const void* mParameterType = nullptr;
		/** Private bound-parameter schema generated by the class base for description and execution. */
		const void* mPreparedParameterType = nullptr;
		/** Encode only the public, portable parameter fields and logical connections. */
		eastl::function<FArdaRHIStatus(const void*, FArdaGraphArchiveWriter&)> mSerializeParameters;
		/** Reconstruct public parameters using graph-local archive resource and node identities. */
		eastl::function<TArdaRHIResult<eastl::shared_ptr<const void>>(FArdaGraphArchiveReader&)> mDeserializeParameters;
		/** Optional recursive graph content builder, invoked with frozen public parameters during compilation. */
		eastl::function<FArdaRHIStatus(FArdaSubgraphContext&, const void*)> mExpand;
		/** Read-only preflight on public parameters, before output declarations or device preparation.
		 * Empty means no explicit requirements. Called on matching reattachment as well.
		 */
		eastl::function<FArdaDependencyNodeRequirements(const void*)> mGetRequirements;
		/** Intrinsic execution-domain/stage requirements, separate from device-independent author requirements. */
		eastl::function<void(FArdaDependencyNodeRequirements&)> mAddIntrinsicRequirements;
		/** Optional immutable compute lowering of a CUDA definition. Selected before any preparation. */
		eastl::shared_ptr<const FArdaDependencyNodeExecutable> mComputeAlternative;
		/** Resolves node-owned outputs before canonical identity and preparation. */
		eastl::function<TArdaRHIResult<eastl::shared_ptr<const void>>(FArdaDependencyResourceContext&,
		    eastl::shared_ptr<const void>)>
		    mResolveResources;
		/** Immutable declaration preparation; does not create mutable execution instances. */
		eastl::function<TArdaRHIResult<eastl::shared_ptr<const void>>(FArdaRHIDeviceRef, eastl::shared_ptr<const void>)>
		    mPrepareDeclaration;
		/** Compiler-owned execution preparation, including a fresh mutable instance. */
		eastl::function<TArdaRHIResult<eastl::shared_ptr<const void>>(FArdaRHIDeviceRef, eastl::shared_ptr<const void>)>
		    mPrepare;
		eastl::function<eastl::string(const void*)> mCanonicalKey;
		eastl::function<TArdaRHIResult<FArdaDependencyNodeDesc>(const void*)> mDescribe;
		eastl::function<FArdaRHIStatus(FArdaDependencyExecutionContext&, const void*)> mRecord;
		/** Per-stage dynamic state, called once in each consuming draw with the terminal's resource context. */
		eastl::function<FArdaRHIStatus(FArdaDependencyExecutionContext&, const void*, FArdaGraphicsWork&)>
		    mConfigureGraphics;
		/** Stage contract permitting automatic instancing; arbitrary native Record hooks are never merged. */
		EArdaGraphicsInstancing mGraphicsInstancing = EArdaGraphicsInstancing::Disabled;
		/** Clone private mutable state for a particular assembled draw while sharing immutable preparation. */
		eastl::function<TArdaRHIResult<eastl::shared_ptr<const void>>(const void*)> mCloneGraphicsParameters;
		/** Optional explicit materialization adapter. Value contains frozen public parameters, not execution state. */
		eastl::function<FArdaGraphBuffer(FArdaGraphEdit&, const void*, const FArdaStageBufferRequest&)> mFetchBuffer;
		eastl::function<FArdaRHIStatus(FArdaDependencyExecutionContext&, const void*, FArdaCudaSequence&)> mPrepareCuda;
	};

	template <class T>
	inline const uint8_t ArdaDependencyParameterType = 0;

	/** Process-wide registry. Lookup returns retained immutable definitions; registration is synchronized. */
	class FArdaNodeRegistry final
	{
	public:
		static FArdaNodeRegistry& Get();
		/** Removes library lookup; existing graph instances retain their immutable definition. */
		FArdaRHIStatus Unregister(const eastl::string& Name);
		eastl::shared_ptr<const FArdaDependencyNodeExecutable> Find(const eastl::string& Name) const;
		eastl::vector<eastl::string> GetNames() const;

	private:
		template <class Derived, class Parameters, EArdaDependencyNodeKind Kind>
		friend class node_detail::TArdaExecutionNode;
		friend class FArdaRuntimeNodeDefinition;
		friend class FArdaGraphSerialization;

		FArdaRHIStatus RegisterExecutable(FArdaDependencyNodeExecutable Executable);
		/** Atomically admit portable definitions; equivalent registrations retain the original identity. */
		FArdaRHIStatus RegisterPortableDefinitions(
		    const eastl::vector<eastl::shared_ptr<const FArdaDependencyNodeExecutable>>& Definitions);
		mutable std::mutex mMutex;
		eastl::unordered_map<eastl::string, eastl::shared_ptr<const FArdaDependencyNodeExecutable>> mDefinitions;
	};
}
